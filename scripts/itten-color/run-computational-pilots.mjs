#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";

const root = process.cwd();
const outDir = path.join(root, "content/projects/itten-color-contrasts/experiments/data");
fs.mkdirSync(outDir, { recursive: true });
const seed = 20260728;

function mulberry32(a) {
  return () => {
    a |= 0; a = a + 0x6D2B79F5 | 0;
    let t = Math.imul(a ^ a >>> 15, 1 | a);
    t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t;
    return ((t ^ t >>> 14) >>> 0) / 4294967296;
  };
}
const rng = mulberry32(seed);
const clamp = (x, lo = 0, hi = 1) => Math.min(hi, Math.max(lo, x));
const mean = xs => xs.reduce((a, b) => a + b, 0) / xs.length;
const sd = xs => {
  const m = mean(xs);
  return Math.sqrt(xs.reduce((s, x) => s + (x - m) ** 2, 0) / (xs.length - 1));
};
const pearson = (a, b) => {
  const ma = mean(a), mb = mean(b);
  const num = a.reduce((s, x, i) => s + (x - ma) * (b[i] - mb), 0);
  const den = Math.sqrt(a.reduce((s, x) => s + (x - ma) ** 2, 0) * b.reduce((s, x) => s + (x - mb) ** 2, 0));
  return num / den;
};
const rank = xs => xs.map((x, i) => ({ x, i })).sort((a, b) => a.x - b.x).reduce((r, v, i) => (r[v.i] = i + 1, r), []);
const spearman = (a, b) => pearson(rank(a), rank(b));
const q = (xs, p) => [...xs].sort((a, b) => a - b)[Math.floor((xs.length - 1) * p)];
const round = (x, n = 4) => Number(x.toFixed(n));

function hexRgb(hex) {
  const s = hex.replace("#", "");
  return [0, 2, 4].map(i => parseInt(s.slice(i, i + 2), 16) / 255);
}
function lin(v) { return v <= .04045 ? v / 12.92 : ((v + .055) / 1.055) ** 2.4; }
function gam(v) { return v <= .0031308 ? 12.92 * v : 1.055 * v ** (1 / 2.4) - .055; }
function xyz(rgb) {
  const [r, g, b] = rgb.map(lin);
  return [
    .4124564*r + .3575761*g + .1804375*b,
    .2126729*r + .7151522*g + .0721750*b,
    .0193339*r + .1191920*g + .9503041*b
  ];
}
function lab(rgb) {
  const [x, y, z] = xyz(rgb);
  const f = t => t > 216/24389 ? Math.cbrt(t) : (24389/27*t + 16)/116;
  const fx=f(x/.95047), fy=f(y), fz=f(z/1.08883);
  return [116*fy-16, 500*(fx-fy), 200*(fy-fz)];
}
function oklab(rgb) {
  const [r,g,b] = rgb.map(lin);
  const l=.4122214708*r+.5363325363*g+.0514459929*b;
  const m=.2119034982*r+.6806995451*g+.1073969566*b;
  const s=.0883024619*r+.2817188376*g+.6299787005*b;
  const l_=Math.cbrt(l), m_=Math.cbrt(m), s_=Math.cbrt(s);
  return [
    .2104542553*l_+.793617785*m_-.0040720468*s_,
    1.9779984951*l_-2.428592205*m_+.4505937099*s_,
    .0259040371*l_+.7827717662*m_-.808675766*s_
  ];
}
const dist = (a,b) => Math.hypot(...a.map((x,i)=>x-b[i]));
const luminance = rgb => xyz(rgb)[1];
const contrast = (a,b) => (Math.max(luminance(a),luminance(b))+.05)/(Math.min(luminance(a),luminance(b))+.05);
const mat = (m,v) => m.map(row => clamp(row.reduce((s,x,i)=>s+x*v[i],0)));
const protan = [[.152286,1.052583,-.204868],[.114503,.786281,.099216],[-.003882,-.048116,1.051998]];
const deutan = [[.367322,.860646,-.227968],[.280085,.672501,.047413],[-.01182,.04294,.968881]];
const tritan = [[1.255528,-.076749,-.178779],[-.078411,.930809,.147602],[.004733,.691367,.3039]];

const metadata = {
  generated: "2026-07-28",
  seed,
  execution_class: "deterministic computational pilot",
  warning: "No human participants or physical display measurements. Outputs validate analysis pipelines and generate predictions; they are not psychophysical findings.",
  script_sha256: crypto.createHash("sha256").update(fs.readFileSync(new URL(import.meta.url))).digest("hex")
};

// EX-01: factorial salience/area model sensitivity.
const ex1rows = [];
for (const area of [.02,.05,.1,.2])
for (const dL of [.05,.15,.3,.6])
for (const dC of [.02,.1,.25])
for (const pos of [.2,.5,.8])
for (const semantic of [0,1]) {
  const centerBias = 1 + .12 * (1 - Math.abs(pos-.5)/.5);
  const score = area**.62 * Math.hypot(3.2*dL, 1.7*dC) * centerBias * (1+.55*semantic);
  ex1rows.push({area,dL,dC,pos,semantic,score});
}
const ex1 = {
  ...metadata, id:"EX-ITTEN-001", n_conditions:ex1rows.length,
  result:{
    correlations:{
      area:round(pearson(ex1rows.map(x=>x.area),ex1rows.map(x=>x.score))),
      luminance_difference:round(pearson(ex1rows.map(x=>x.dL),ex1rows.map(x=>x.score))),
      chroma_difference:round(pearson(ex1rows.map(x=>x.dC),ex1rows.map(x=>x.score))),
      semantic_priority:round(pearson(ex1rows.map(x=>x.semantic),ex1rows.map(x=>x.score)))
    },
    score_range:[round(Math.min(...ex1rows.map(x=>x.score))),round(Math.max(...ex1rows.map(x=>x.score)))],
    falsification_note:"Because the score is generated by an explicit salience proxy, this is a pipeline/sensitivity test and cannot validate the proxy or Itten's area ratios."
  }
};

// EX-02: token metrics and contextual induction proxy.
const palette = ["#0057B8","#D7191C","#2C7A3F","#F2C94C","#7B2CBF","#00A6A6","#6B7280","#F8FAFC","#111827","#FF7A00","#E83E8C","#7DD3FC"];
const backgrounds = ["#FFFFFF","#F3F4F6","#111827","#000000","#FFF4D6","#DDEBFF"];
const ex2rows=[];
for(const fgHex of palette) for(const bgHex of backgrounds){
  const fg=hexRgb(fgHex), bg=hexRgb(bgHex);
  const l=lab(fg), bl=lab(bg), o=oklab(fg), bo=oklab(bg);
  // Simple opponent surround proxy: target appearance shifts 8% away from surround.
  const induced=l.map((v,i)=>v+.08*(v-bl[i]));
  ex2rows.push({fg:fgHex,bg:bgHex,wcag:contrast(fg,bg),lab:dist(l,bl),oklab:dist(o,bo),induction_shift:dist(l,induced)});
}
const wcag=ex2rows.map(x=>x.wcag), dl=ex2rows.map(x=>x.lab), dok=ex2rows.map(x=>x.oklab);
const ex2={...metadata,id:"EX-ITTEN-002",n_pairs:ex2rows.length,result:{
  spearman:{wcag_vs_lab:round(spearman(wcag,dl)),wcag_vs_oklab:round(spearman(wcag,dok)),lab_vs_oklab:round(spearman(dl,dok))},
  pass_4_5:ex2rows.filter(x=>x.wcag>=4.5).length,
  pass_3:ex2rows.filter(x=>x.wcag>=3).length,
  induction_shift_deltaE76:{median:round(q(ex2rows.map(x=>x.induction_shift),.5)),max:round(Math.max(...ex2rows.map(x=>x.induction_shift)))},
  interpretation:"Metric rankings disagree because they describe different constructs. The induction values are model-generated stress indicators, not observed appearance shifts."
}};

// EX-03: HDR adaptation proxy. Recovery threshold after a flash.
const ex3rows=[];
for(const peak of [200,600,1000,2000])
for(const field of [.01,.1,.4])
for(const ambient of [0,50,200,1000]){
  const adaptationLoad=Math.log10(1+peak/100)*field**.45;
  const tau=1.8+4.2*adaptationLoad+Math.log10(1+ambient)*.5;
  const initialLoss=clamp(.08+.35*adaptationLoad,0,.85);
  const t90=-tau*Math.log(.1);
  ex3rows.push({peak,field,ambient,tau,initialLoss,t90});
}
const ex3={...metadata,id:"EX-ITTEN-003",n_conditions:ex3rows.length,result:{
  predicted_t90_seconds:{median:round(q(ex3rows.map(x=>x.t90),.5)),p95:round(q(ex3rows.map(x=>x.t90),.95)),max:round(Math.max(...ex3rows.map(x=>x.t90)))},
  predicted_initial_sensitivity_loss:{median:round(q(ex3rows.map(x=>x.initialLoss),.5)),max:round(Math.max(...ex3rows.map(x=>x.initialLoss)))},
  status:"model-only; requires measured thresholds before/after controlled flashes"
}};

// EX-04: CVD + aging robustness audit with redundant encoding.
const ex4rows=[];
for(const aHex of palette) for(const bHex of palette) if(aHex<bHex){
  const a=hexRgb(aHex),b=hexRgb(bHex);
  for(const [vision,matrix] of [["typical",null],["protan",protan],["deutan",deutan],["tritan",tritan]]){
    for(const age of [25,65,80]){
      let aa=matrix?mat(matrix,a):a, bb=matrix?mat(matrix,b):b;
      const yellowing=clamp((age-25)/110,0,.5);
      aa=[aa[0],aa[1],aa[2]*(1-yellowing)]; bb=[bb[0],bb[1],bb[2]*(1-yellowing)];
      const d=dist(oklab(aa),oklab(bb));
      ex4rows.push({a:aHex,b:bHex,vision,age,delta_ok:d,color_detectable:d>=.08,redundant_shape_detectable:true});
    }
  }
}
const groups={};
for(const vision of ["typical","protan","deutan","tritan"]) for(const age of [25,65,80]){
  const xs=ex4rows.filter(x=>x.vision===vision&&x.age===age);
  groups[`${vision}_${age}`]=round(xs.filter(x=>x.color_detectable).length/xs.length);
}
const ex4={...metadata,id:"EX-ITTEN-004",n_observer_pair_conditions:ex4rows.length,result:{
  modeled_color_pair_detection_rate:groups,
  redundant_shape_detection_rate:1,
  warning:"The 0.08 Oklab cutoff, CVD matrices, and lens-yellowing transform are screening assumptions, not clinical thresholds."
}};

// EX-05: multilingual warm/cool study power/readiness simulation.
const ex5rows=[];
for(const nPerGroup of [30,60,120,240]) {
  let detected=0;
  for(let sim=0;sim<2000;sim++){
    const effect=.25; // standardized interaction
    const se=Math.sqrt(2/nPerGroup);
    const z=effect/se + (rng()+rng()+rng()+rng()+rng()+rng()-3);
    if(Math.abs(z)>1.96) detected++;
  }
  ex5rows.push({n_per_group:nPerGroup,simulated_power:detected/2000});
}
const ex5={...metadata,id:"EX-ITTEN-005",result:{
  power_simulation:ex5rows,
  recommendation:"The toy simulation reaches approximately 86% power only at 240 analyzable participants per language/climate stratum. Use 240 as the provisional planning value, then replace it with a formal mixed-model power analysis using empirical pilot variance.",
  status:"protocol-ready; no survey responses collected"
}};

// EX-06: emitted-match device/ambient black-level proxy.
const ex6rows=[];
for(const device of [{name:"OLED",black:.0005,reflectance:.012},{name:"LCD",black:.08,reflectance:.025}])
for(const ambient of [0,50,200,1000])
for(const white of [100,300,600]){
  const reflected=ambient*device.reflectance/Math.PI;
  const effectiveBlack=device.black+reflected;
  const effectiveWhite=white+reflected;
  ex6rows.push({device:device.name,ambient,white,effectiveBlack,effectiveContrast:effectiveWhite/effectiveBlack});
}
const ex6={...metadata,id:"EX-ITTEN-006",n_conditions:ex6rows.length,result:{
  contrast_by_condition:Object.fromEntries(ex6rows.map(x=>[`${x.device}_${x.ambient}lux_${x.white}nit`,round(x.effectiveContrast,1)])),
  interpretation:"Matched emitted white does not imply matched effective contrast once black level and ambient reflection differ.",
  status:"parameter sweep; requires spectroradiometer/photometer measurements on named devices"
}};

// EX-07: peripheral cue proxy and required redundancy.
const ex7rows=[];
for(const ecc of [0,5,10,20,30])
for(const size of [.1,.25,.5,1,2])
for(const chroma of [.05,.1,.2,.35]){
  const sensitivity=Math.exp(-ecc/18)*(1-Math.exp(-size/Math.max(.12,.15+ecc*.02)))*Math.sqrt(chroma/.05);
  ex7rows.push({ecc,size,chroma,sensitivity,detectable:sensitivity>=.55});
}
const minima={};
for(const ecc of [0,5,10,20,30]) for(const chroma of [.05,.1,.2,.35]){
  const hit=ex7rows.filter(x=>x.ecc===ecc&&x.chroma===chroma&&x.detectable).sort((a,b)=>a.size-b.size)[0];
  minima[`${ecc}deg_chroma${chroma}`]=hit?.size??null;
}
const ex7={...metadata,id:"EX-ITTEN-007",n_conditions:ex7rows.length,result:{
  modeled_minimum_size_degrees:minima,
  interpretation:"The proxy predicts rapidly worsening hue-only cue reliability with eccentricity; null means no tested size passed.",
  status:"model-only; requires gaze-contingent psychophysics"
}};

// EX-08: metric stability under gamut compression.
const ex8rows=[];
for(let i=0;i<3000;i++){
  const a=[rng(),rng(),rng()], b=[rng(),rng(),rng()];
  const compress=v=>v.map(x=>clamp(.06+.88*x));
  ex8rows.push({
    lab:dist(lab(a),lab(b)),ok:dist(oklab(a),oklab(b)),
    labCompressed:dist(lab(compress(a)),lab(compress(b))),
    okCompressed:dist(oklab(compress(a)),oklab(compress(b))),
    lum:Math.abs(luminance(a)-luminance(b))
  });
}
const ex8={...metadata,id:"EX-ITTEN-008",n_pairs:ex8rows.length,result:{
  rank_stability_after_gamut_compression:{
    lab:round(spearman(ex8rows.map(x=>x.lab),ex8rows.map(x=>x.labCompressed))),
    oklab:round(spearman(ex8rows.map(x=>x.ok),ex8rows.map(x=>x.okCompressed)))
  },
  cross_metric_rank_correlation:round(spearman(ex8rows.map(x=>x.lab),ex8rows.map(x=>x.ok))),
  correlation_with_luminance_difference:{lab:round(pearson(ex8rows.map(x=>x.lab),ex8rows.map(x=>x.lum))),oklab:round(pearson(ex8rows.map(x=>x.ok),ex8rows.map(x=>x.lum)))},
  status:"computational stress test only; no perceptual ground truth, CAM16-UCS, ΔE00, or HDR measurements yet"
}};

const all=[ex1,ex2,ex3,ex4,ex5,ex6,ex7,ex8];
for(const ex of all) fs.writeFileSync(path.join(outDir,`${ex.id.toLowerCase()}.json`),JSON.stringify(ex,null,2)+"\n");
fs.writeFileSync(path.join(outDir,"computational-pilot-summary.json"),JSON.stringify({metadata,experiments:all.map(({id,n_conditions,n_pairs,n_observer_pair_conditions,result})=>({id,n_conditions,n_pairs,n_observer_pair_conditions,result}))},null,2)+"\n");
console.log(JSON.stringify({ok:true,seed,experiments:all.length,output:outDir,script_sha256:metadata.script_sha256},null,2));
